package compose

import (
	"fmt"
	"strings"

	"github.com/Herculade0/feldcore/internal/docker"
)

// Override is the second compose file FELDCORE writes beside the user's.
// It labels every service and, when the user's file does not define
// networks, pins the default network to this stack's bridge (or to the
// shared bridge when isolation is off).
func Override(compose string, stack string, isolate bool) (string, string, error) {
	f, err := parse(compose)
	if err != nil {
		return "", "", err
	}
	var b strings.Builder
	b.WriteString("# Generated by FELDCORE. Recreated when the stack is saved or deployed.\n")
	b.WriteString("services:\n")
	for _, s := range f.services {
		fmt.Fprintf(&b, "  %s:\n    labels:\n      %s: \"true\"\n      %s: %q\n",
			yamlKey(s.name), docker.ManagedLabel, docker.StackLabel, stack)
	}
	network := ""
	if !f.hasNets {
		if isolate {
			network = docker.StackNetwork(stack)
		} else {
			network = "bridge"
		}
		fmt.Fprintf(&b, "networks:\n  default:\n    name: %s\n    external: true\n", network)
	}
	return b.String(), network, nil
}

func yamlKey(s string) string {
	if svcNameRe.MatchString(s) && !strings.ContainsAny(s, ":#") {
		return s
	}
	return fmt.Sprintf("%q", s)
}
